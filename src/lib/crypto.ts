import { createCipheriv, createDecipheriv, createHash, randomBytes } from "node:crypto";
import { requiredEnv } from "@/lib/env";
import { ConfigurationError } from "@/lib/errors";

function encryptionKey(): Buffer {
  return createHash("sha256").update(requiredEnv("AUTH_SECRET"), "utf8").digest();
}

export function encryptSecret(value: string): string {
  const iv = randomBytes(12);
  const cipher = createCipheriv("aes-256-gcm", encryptionKey(), iv);
  const ciphertext = Buffer.concat([cipher.update(value, "utf8"), cipher.final()]);
  return ["v1", iv.toString("base64url"), cipher.getAuthTag().toString("base64url"), ciphertext.toString("base64url")].join(".");
}

export function decryptSecret(value: string): string {
  const [version, ivValue, tagValue, ciphertextValue] = value.split(".");
  if (version !== "v1" || !ivValue || !tagValue || !ciphertextValue) throw new ConfigurationError("Stored credential has an unsupported format");
  try {
    const decipher = createDecipheriv("aes-256-gcm", encryptionKey(), Buffer.from(ivValue, "base64url"));
    decipher.setAuthTag(Buffer.from(tagValue, "base64url"));
    return Buffer.concat([decipher.update(Buffer.from(ciphertextValue, "base64url")), decipher.final()]).toString("utf8");
  } catch {
    throw new ConfigurationError("Stored GitHub credential could not be decrypted; sign in again");
  }
}
